//! State shared by the layers while the pipeline runs.

use std::path::PathBuf;

use crate::{binding::Binding, ids::SessionId, plan::Plan};

/// A Wine prefix's user dirs, as the Compat layer set it up.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WinePrefix {
    /// The prefix's `drive_c`.
    pub drive_c: PathBuf,
    /// The Windows user name (`steamuser` under Proton).
    pub user: String,
}

impl WinePrefix {
    /// `drive_c/users/<user>`.
    pub fn user_dir(&self) -> PathBuf {
        self.drive_c.join("users").join(&self.user)
    }
}

/// Identity and scratch space of one launch session.
#[derive(Debug, Clone)]
pub struct SessionInfo {
    /// Unique id of this session, generated by the executor.
    pub id: SessionId,
    /// Session-private scratch directory (not necessarily created yet).
    pub tmp_dir: PathBuf,
}

/// Whether the pipeline performs real side effects.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RunKind {
    /// `explain`: layers must not touch the filesystem or spawn anything.
    DryRun,
    /// A real launch.
    Live,
}

/// Mutable state shared across layers while the pipeline runs (`stdg-exec`).
#[derive(Debug)]
pub struct LaunchCtx {
    /// The validated plan being executed.
    pub plan: Plan,
    /// The session this launch belongs to.
    pub session: SessionInfo,
    /// Bindings requested by inner layers so far.
    pub bindings: Vec<Binding>,
    /// Dry run or live launch.
    pub run_kind: RunKind,
    /// Set from the Compat layer's [`crate::Layer::wine_prefix`].
    pub wine_prefix: Option<WinePrefix>,
}

impl LaunchCtx {
    /// Shorthand for `self.run_kind == RunKind::DryRun`.
    pub fn is_dry_run(&self) -> bool {
        self.run_kind == RunKind::DryRun
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use super::*;
    use crate::{GameId, ModeId, ResolvedConfig, RunnerId, TargetKind};

    fn ctx(run_kind: RunKind) -> LaunchCtx {
        let config = ResolvedConfig {
            app_id: None,
            game_id: GameId("g".to_string()),
            target: TargetKind::NativeLinux,
            root: PathBuf::from("/games/g"),
            executable: PathBuf::from("g"),
            args: vec![],
            command_prefix: vec![],
            env: BTreeMap::new(),
            saves: crate::SavesConfig::default(),
        };
        LaunchCtx {
            plan: Plan {
                game_id: config.game_id.clone(),
                mode_id: ModeId("m".to_string()),
                target: config.target.clone(),
                runner: RunnerId("native-linux".to_string()),
                slots: BTreeMap::new(),
                config,
            },
            session: SessionInfo {
                id: SessionId("s".to_string()),
                tmp_dir: PathBuf::from("/nonexistent"),
            },
            bindings: Vec::new(),
            run_kind,
            wine_prefix: None,
        }
    }

    #[test]
    fn is_dry_run_reflects_run_kind() {
        assert!(ctx(RunKind::DryRun).is_dry_run());
        assert!(!ctx(RunKind::Live).is_dry_run());
    }
}
